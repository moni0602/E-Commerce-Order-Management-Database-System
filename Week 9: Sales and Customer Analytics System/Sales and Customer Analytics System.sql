-- =========================================================
-- 8. BUSINESS ANALYTICS REPORT 2
-- CUSTOMER ANALYTICS REPORT
-- =========================================================

SELECT
    c.Customer_Name,
    COUNT(o.Order_ID) AS Number_Of_Orders,
    SUM(o.Total_Amount) AS Total_Spending,
    COUNT(o.Order_ID) AS Purchase_Frequency
FROM customers c
JOIN orders o
ON c.Customer_ID = o.Customer_ID
GROUP BY c.Customer_ID, c.Customer_Name
ORDER BY Total_Spending DESC;


-- =========================================================
-- 9. BUSINESS ANALYTICS REPORT 3
-- PRODUCT PERFORMANCE REPORT
-- =========================================================

SELECT
    p.Product_Name,
    SUM(od.Quantity) AS Quantity_Sold,
    SUM(od.Quantity * od.Price) AS Revenue_Generated
FROM products p
JOIN Order_Details od
ON p.Product_ID = od.Product_ID
GROUP BY p.Product_ID, p.Product_Name
ORDER BY Revenue_Generated DESC;


-- =========================================================
-- 10. BUSINESS ANALYTICS REPORT 4
-- CATEGORY ANALYSIS REPORT
-- =========================================================

SELECT
    c.Category_Name,
    SUM(od.Quantity) AS Total_Products_Sold,
    SUM(od.Quantity * od.Price) AS Total_Revenue
FROM categories c
JOIN products p
ON c.Category_ID = p.Category_ID
JOIN Order_Details od
ON p.Product_ID = od.Product_ID
GROUP BY c.Category_ID, c.Category_Name
ORDER BY Total_Revenue DESC;
