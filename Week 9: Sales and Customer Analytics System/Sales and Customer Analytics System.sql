-- =========================================================
-- 6. CATEGORY-WISE SALES ANALYSIS
-- =========================================================

-- 1. Total sales generated by each category
SELECT
    p.Category_ID,
    SUM(od.Quantity * od.Price) AS Category_Sales
FROM products p
JOIN Order_Details od
ON p.Product_ID = od.Product_ID
GROUP BY p.Category_ID
ORDER BY Category_Sales DESC;

-- 2. Number of products sold in each category
SELECT
    p.Category_ID,
    SUM(od.Quantity) AS Total_Products_Sold
FROM products p
JOIN Order_Details od
ON p.Product_ID = od.Product_ID
GROUP BY p.Category_ID
ORDER BY Total_Products_Sold DESC;

-- 3. Highest revenue-generating category
SELECT
    p.Category_ID,
    SUM(od.Quantity * od.Price) AS Total_Revenue
FROM products p
JOIN Order_Details od
ON p.Product_ID = od.Product_ID
GROUP BY p.Category_ID
ORDER BY Total_Revenue DESC
LIMIT 1;

-- 4. Average sales per category
SELECT
    p.Category_ID,
    AVG(od.Quantity * od.Price) AS Average_Sales
FROM products p
JOIN Order_Details od
ON p.Product_ID = od.Product_ID
GROUP BY p.Category_ID
ORDER BY Average_Sales DESC;


