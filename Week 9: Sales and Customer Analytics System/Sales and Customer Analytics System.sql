-- =========================================================
-- 3. CUSTOMER PURCHASE ANALYSIS
-- =========================================================

-- 1. Total number of orders placed by each customer
SELECT
    Customer_ID,
    COUNT(*) AS Total_Orders
FROM orders
GROUP BY Customer_ID;

-- 2. Total amount spent by each customer
SELECT
    Customer_ID,
    SUM(Total_Amount) AS Total_Spending
FROM orders
GROUP BY Customer_ID;

-- 3. Average spending per customer
SELECT
    Customer_ID,
    AVG(Total_Amount) AS Average_Spending
FROM orders
GROUP BY Customer_ID;

-- 4. Customers with maximum purchase amount
SELECT
    Customer_ID,
    SUM(Total_Amount) AS Total_Spending
FROM orders
GROUP BY Customer_ID
ORDER BY Total_Spending DESC;

-- 5. Customers with fewer purchases
SELECT
    Customer_ID,
    COUNT(*) AS Total_Orders
FROM orders
GROUP BY Customer_ID
ORDER BY Total_Orders ASC;


-- =========================================================
-- 4. TOP CUSTOMERS BASED ON PURCHASE AMOUNT
-- =========================================================

-- 1. Top 5 customers based on total spending
SELECT
    Customer_ID,
    SUM(Total_Amount) AS Total_Spending
FROM orders
GROUP BY Customer_ID
ORDER BY Total_Spending DESC
LIMIT 5;

-- 2. Customers with maximum number of orders
SELECT
    Customer_ID,
    COUNT(*) AS Total_Orders
FROM orders
GROUP BY Customer_ID
ORDER BY Total_Orders DESC;

-- 3. Frequent customers
SELECT
    Customer_ID,
    COUNT(*) AS Purchase_Frequency
FROM orders
GROUP BY Customer_ID
HAVING COUNT(*) > 1
ORDER BY Purchase_Frequency DESC;

-- 4. High-value customers
SELECT
    Customer_ID,
    SUM(Total_Amount) AS Total_Spending
FROM orders
GROUP BY Customer_ID
HAVING SUM(Total_Amount) > 10000
ORDER BY Total_Spending DESC;


